<?php

namespace Splicewire\Beam\Config\Generator;

use Nette\PhpGenerator\Literal;
use Nette\PhpGenerator\PhpFile;
use Nette\PhpGenerator\PsrPrinter;
use Schemastud\DataSchemas\Attributes\ArrayItems;
use Schemastud\DataSchemas\Attributes\Description;
use Schemastud\DataSchemas\Attributes\Keyword;
use Schemastud\DataSchemas\Attributes\MapValues;
use Schemastud\DataSchemas\Attributes\Title;
use Spatie\LaravelData\Attributes\Validation\In;
use Spatie\LaravelData\Data;
use Spatie\LaravelData\Optional;
use Splicewire\Beam\Config\Attributes\ConfigDraft;
use Splicewire\Beam\Config\Attributes\ConfigKey;
use Splicewire\Beam\Config\Attributes\ConfigOpaque;
use Splicewire\Beam\Config\Attributes\ConfigRoot;
use Splicewire\Beam\Config\ConfigSection;

/**
 * Prints an {@see InferredSection} as PHP source, one file per class (config-sections ticket 06), with
 * nette/php-generator, the way rushing/laravel-codegen's `DataClassGenerator` prints Data classes.
 */
class ConfigSectionEmitter
{
    /**
     * @return array<string, string> short class name => source
     */
    public function emit(InferredSection $section, string $namespace, string $source): array
    {
        $files = [];

        foreach ($section->classes as $class => $keys) {
            $file = new PhpFile;
            $space = $file->addNamespace($namespace);
            $type = $space->addClass($class);
            $isSection = $class === $section->sectionClass;
            $pointer = $section->pointers[$class] ?? '';

            if ($isSection) {
                $space->addUse(ConfigSection::class)->addUse(ConfigRoot::class);
                $type->setExtends(ConfigSection::class);
                $type->addAttribute(ConfigRoot::class, array_filter([
                    'root' => $section->root,
                    'title' => $section->title,
                    'entries' => $section->entries === null ? null : new Literal($section->entries.'::class'),
                ], fn (mixed $value): bool => $value !== null));
                $type->addComment(sprintf('The `%s` Config Section (ADR-0245), generated by `splicewire:beam:make:config-section` from %s.', $section->root, $source));
                $type->addComment('');
                $type->addComment('Every key is deploy-only and not overridable until it is opted in. The titles and descriptions marked');
                $type->addComment('#[ConfigDraft] were harvested from the config file: rewrite them, then delete the marker.');
            } else {
                $space->addUse(Data::class);
                $type->setExtends(Data::class);
                $type->addComment(sprintf('`%s%s` (generated with {@see %s}).', $section->root, $pointer === '' ? '' : ' '.$pointer, $section->sectionClass));
            }

            $constructor = $type->addMethod('__construct');

            foreach ($keys as $key) {
                $this->property($constructor->addPromotedParameter($key->name), $key, $space, $namespace);
            }

            $files[$class] = (new PsrPrinter)->printFile($file);
        }

        return $files;
    }

    private function property(\Nette\PhpGenerator\PromotedParameter $parameter, InferredKey $key, \Nette\PhpGenerator\PhpNamespace $space, string $namespace): void
    {
        $parameter->setPublic();
        $parameter->setType($this->type($key, $space, $namespace));

        $space->addUse(Title::class)->addUse(Description::class)->addUse(ConfigDraft::class)->addUse(ConfigKey::class);
        $parameter->addAttribute(Title::class, [$key->title]);
        $parameter->addAttribute(Description::class, [$key->description]);
        $parameter->addAttribute(ConfigDraft::class);
        $parameter->addAttribute(ConfigKey::class, $key->env === null ? [] : ['env' => $key->env]);

        if ($key->enum !== null) {
            $space->addUse(In::class);
            $parameter->addAttribute(In::class, [$key->enum]);
        }

        if ($key->widget !== null) {
            $space->addUse(Keyword::class);
            $parameter->addAttribute(Keyword::class, ['x-widget', 'combobox']);
            $parameter->addAttribute(Keyword::class, ['x-widget-options', $key->widget]);
        }

        if ($key->mapValues !== null) {
            $space->addUse(MapValues::class);
            $parameter->addAttribute(MapValues::class, $key->mapValues === '' ? [] : [$this->valueType($key->mapValues)]);
        }

        if ($key->arrayItems !== null) {
            $space->addUse(ArrayItems::class);
            $parameter->addAttribute(ArrayItems::class, [$key->arrayItems]);
        }

        if ($key->opaque !== null) {
            $space->addUse(ConfigOpaque::class);
            $parameter->addAttribute(ConfigOpaque::class, [$key->opaque]);
        }
    }

    private function type(InferredKey $key, \Nette\PhpGenerator\PhpNamespace $space, string $namespace): string
    {
        $type = $key->type;

        // A sibling class is named relative to the section's namespace.
        if (preg_match('/^[A-Z]\w*$/', $type) === 1) {
            $type = $namespace.'\\'.$type;
        }

        if (! $key->optional || $type === 'mixed') {
            return $type;
        }

        $space->addUse(Optional::class);
        $nullable = str_starts_with($type, '?');
        $type = ltrim($type, '?');

        return $type.'|'.Optional::class.($nullable ? '|null' : '');
    }

    /** A map's value type: a JSON type token stays a string; a sibling class is a `::class` reference. */
    private function valueType(string $type): string|Literal
    {
        return in_array($type, ['string', 'integer', 'number', 'boolean'], true) ? $type : new Literal($type.'::class');
    }
}
