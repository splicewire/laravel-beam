<?php

namespace Splicewire\Beam\Codegen;

use Splicewire\Beam\Particle\Contribution\ResourceContributionRegistry;
use Splicewire\Beam\Particle\ParticleOperationRegistry;
use Splicewire\Beam\Particle\ParticleResource;
use Splicewire\Beam\Particle\ParticleResourceRegistry;

/**
 * Project addressable particle declarations into the host's opt-in frame resource type map.
 * Registries in, source and warnings out; the client command owns reference resolution and disk writes.
 * Action declarations are included before mount filtering, so this is a superset of each realm's buttons.
 *
 * @phpstan-type Entry array{row: string, edit: string, createResult: string, publicRead: string|null, slices: array<string, array{data: string, nullable: bool}>, actions: array<string, string|null>}
 * @phpstan-type Reference array{name: string, module?: string}
 */
class FrameResourceTypesGenerator
{
    public function __construct(
        protected ParticleResourceRegistry $resources,
        protected ParticleOperationRegistry $operations,
        protected ResourceContributionRegistry $contributions,
    ) {}

    /** @return array<string, Entry> */
    public function derive(): array
    {
        $contributed = (new ContributedTypesGenerator($this->resources, $this->contributions))->derive();
        $entries = [];
        foreach ($this->resources->unfiltered()->matches('beam.particle.resources') as $resource) {
            if (! $resource instanceof ParticleResource || ! $this->resources->hasAddressableResource($resource->key)) {
                continue;
            }
            $definition = $this->resources->definition($resource->key);
            $actions = [];
            foreach ($this->operations->forResource($resource->key) as $operation) {
                if ($operation->actionAffordance() !== null) {
                    $actions[$operation->name] = is_string($operation->input) ? $operation->input : null;
                }
            }
            ksort($actions);
            $slices = $contributed[$resource->key]['slices'] ?? [];
            ksort($slices);
            $entries[$resource->key] = [
                'row' => $definition->data,
                'edit' => $definition->editData ?? $definition->data,
                'createResult' => $definition->createResultData ?? $definition->data,
                'publicRead' => $resource->publicRead !== $definition->data ? $resource->publicRead : null,
                'slices' => $slices,
                'actions' => $actions,
            ];
        }
        ksort($entries);

        return $entries;
    }

    /**
     * @param  array<string, Entry>  $entries
     * @return list<string>
     */
    public function classes(array $entries): array
    {
        $classes = [];
        foreach ($entries as $entry) {
            array_push($classes, $entry['row'], $entry['edit'], $entry['createResult']);
            if ($entry['publicRead'] !== null) {
                $classes[] = $entry['publicRead'];
            }
            foreach ($entry['slices'] as $slice) {
                $classes[] = $slice['data'];
            }
            foreach ($entry['actions'] as $class) {
                if ($class !== null) {
                    $classes[] = $class;
                }
            }
        }

        return array_values(array_unique($classes));
    }

    /**
     * @param  array<string, Entry>  $entries
     * @param  array<string, Reference>  $references
     * @param  array<string, string>  $unresolved  Class => reason, as resolveClasses() returns it
     * @return array{contents: string, warnings: list<string>}
     */
    public function render(array $entries, array $references, array $unresolved = []): array
    {
        $lines = ['// GENERATED by `splicewire:beam:generate:client` — do not edit.', 'export interface FrameResources {'];
        $warnings = [];
        foreach ($entries as $key => $entry) {
            $reference = function (string $class) use ($references, $unresolved, $key, &$warnings): string {
                $resolved = $references[$class] ?? null;
                if ($resolved === null) {
                    $reason = $unresolved[str_replace('.', '\\', $class)] ?? 'has no type because no TypeScript transformer is configured';
                    $warnings[$key.'|'.$class] = "Frame resource [{$key}]: [{$class}] {$reason}; typed as Record<string, unknown>.";

                    return 'Record<string, unknown>';
                }

                return isset($resolved['module'])
                    ? 'import('.$this->quote($resolved['module']).').'.$resolved['name']
                    : $resolved['name'];
            };
            $row = $reference($entry['row']);
            $slices = [];
            foreach ($entry['slices'] as $name => $slice) {
                $slices[] = $this->quote($name).': '.$reference($slice['data']).($slice['nullable'] ? ' | null' : '');
            }
            if ($slices !== []) {
                $row .= ' & { '.implode('; ', $slices).' }';
            }
            if ($entry['publicRead'] !== null) {
                $row = ($slices !== [] ? '('.$row.')' : $row).' | '.$reference($entry['publicRead']);
            }
            $actions = [];
            foreach ($entry['actions'] as $name => $class) {
                $actions[] = $this->quote($name).': '.($class === null ? 'null' : $reference($class));
            }
            $lines[] = '    '.$this->quote($key).': {';
            $lines[] = '        row: '.$row.';';
            $lines[] = '        edit: '.$reference($entry['edit']).';';
            $lines[] = '        createResult: '.$reference($entry['createResult']).';';
            $lines[] = '        actions: '.($actions === [] ? '{}' : '{ '.implode('; ', $actions).' }').';';
            $lines[] = '    };';
        }
        $lines[] = '}';

        return ['contents' => implode("\n", $lines)."\n", 'warnings' => array_values($warnings)];
    }

    private function quote(string $value): string
    {
        return "'".str_replace(['\\', "'", "\r", "\n"], ['\\\\', "\\'", '\\r', '\\n'], $value)."'";
    }
}
